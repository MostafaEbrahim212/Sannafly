export function useTranslation() {
    const { locale, dir, auth, settings } = usePage<PageProps>().props;
    const lang: 'en' | 'ar' = locale === 'ar' ? 'ar' : 'en';

    const t = (key: string, fallback?: string): string => {
        return translations[lang][key] ?? fallback ?? key;
    };

    const localized = (enVal?: string | null, arVal?: string | null): string => {
        if (lang === 'ar' && arVal) return arVal;
        return enVal ?? '';
    };

    const can = (permission: string): boolean => {
        if (!auth.user) return false;
        if (auth.user.roles?.includes('super-admin')) return true;
        return auth.permissions?.includes(permission) ?? false;
    };

    const formatPrice = (amount: string | number): string => {
        const symbol = settings.currency_symbol || '$';
        const num = typeof amount === 'string' ? parseFloat(amount) : amount;
        if (Number.isNaN(num)) return `${symbol}0.00`;
        return `${symbol}${num.toFixed(2)}`;
    };

    return { t, localized, can, formatPrice, locale: lang, dir, settings };
}
